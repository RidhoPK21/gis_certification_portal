<div class="guide-section">
    <h3>Bantuan Cepat</h3>
    <div class="faq-accordion">
        <details class="faq-item">
            <summary>Mengapa tombol tertentu tidak muncul?</summary>
            <p>Tombol evaluasi atau verifikasi hanya muncul jika tahapan tersebut termasuk di dalam Lingkup Penugasan Auditor Anda.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa data tidak dapat diedit?</summary>
            <p>Laporan audit atau temuan yang sudah ditutup tidak dapat diubah kembali untuk menjaga integritas hasil penilaian.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa order tidak muncul?</summary>
            <p>Daftar audit hanya menampilkan permohonan yang telah ditugaskan secara resmi kepada akun Anda oleh Admin atau Superadmin.</p>
        </details>
        <details class="faq-item">
            <summary>Apa arti status yang sedang tampil?</summary>
            <p>Status menampilkan tahap evaluasi yang sedang aktif, seperti Audit Tahap 1, Audit Tahap 2, atau proses verifikasi tindakan koreksi.</p>
        </details>
        <details class="faq-item">
            <summary>Siapa yang harus dihubungi jika ada kendala?</summary>
            <p>Jika terdapat kendala pada penugasan atau pembagian scope, silakan hubungi Admin Permohonan atau Superadmin.</p>
        </details>
    </div>
</div>
