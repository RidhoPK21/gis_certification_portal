<div class="guide-section">
    <h3>Mulai dari Sini</h3>
    <div class="step-cards-grid">
        <div class="step-card">
            <span class="step-badge">Langkah 1</span>
            <h4>Membuka Order yang Ditugaskan</h4>
            <p>Buka permohonan sertifikasi yang telah ditugaskan secara resmi kepada Anda melalui daftar audit.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 2</span>
            <h4>Memeriksa Lingkup Penugasan</h4>
            <p>Periksa rincian penugasan Anda pada order tersebut untuk melihat batasan tahapan evaluasi.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 3</span>
            <h4>Memahami Tab Penugasan</h4>
            <p>Gunakan tab pemeriksaan yang aktif sesuai scope penugasan: Stage 1, Stage 2, QMS/Lapangan, atau Corrective Action.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 4</span>
            <h4>Menyimpan Hasil Audit</h4>
            <p>Isi dan simpan catatan evaluasi pada setiap tahapan audit yang menjadi tanggung jawab Anda.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 5</span>
            <h4>Mengunggah Laporan Audit</h4>
            <p>Unggah dokumen laporan akhir evaluasi sebagai bukti pelaksanaan pemeriksaan.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 6</span>
            <h4>Membuat Temuan Ketidaksesuaian</h4>
            <p>Buat temuan perbaikan apabila terdapat ketidaksesuaian pada penerapan sistem atau dokumen Klien.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 7</span>
            <h4>Mereview Corrective Action</h4>
            <p>Periksa jawaban serta bukti perbaikan Klien atas temuan audit hanya jika scope penugasan Anda sesuai.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 8</span>
            <h4>Menyelesaikan Tanpa Temuan</h4>
            <p>Selesaikan pemeriksaan QMS tanpa temuan hanya setelah pemeriksaan QMS berstatus Disetujui.</p>
        </div>
        <div class="step-card">
            <span class="step-badge">Langkah 9</span>
            <h4>Meneruskan ke Tim Teknis</h4>
            <p>Teruskan hasil audit yang telah selesai agar dapat diproses lebih lanjut oleh Tim Teknis sesuai workflow.</p>
        </div>
    </div>
</div>

