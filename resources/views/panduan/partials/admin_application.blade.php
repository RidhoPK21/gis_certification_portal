<div class="guide-section">
    <h3>Bantuan Cepat</h3>
    <div class="faq-accordion">
        <details class="faq-item">
            <summary>Mengapa tombol tertentu tidak muncul?</summary>
            <p>Tombol persetujuan atau permintaan revisi hanya muncul apabila permohonan berada pada tahap pemeriksaan administrasi.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa data tidak dapat diedit?</summary>
            <p>Admin tidak mengubah data Klien secara sepihak untuk menjaga transparansi riwayat. Gunakan fitur permintaan revisi agar Klien yang memperbaikinya.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa order tidak muncul?</summary>
            <p>Pastikan Anda membuka tab filter status yang tepat pada antrean permohonan untuk melihat seluruh berkas masuk.</p>
        </details>
        <details class="faq-item">
            <summary>Apa arti status yang sedang tampil?</summary>
            <p>Status menunjukkan apakah dokumen sedang diperiksa, menunggu perbaikan dari Klien, atau sudah disetujui untuk lanjut ke proses tagihan.</p>
        </details>
        <details class="faq-item">
            <summary>Siapa yang harus dihubungi jika ada kendala?</summary>
