<div class="guide-section">
    <h3>Bantuan Cepat</h3>
    <div class="faq-accordion">
        <details class="faq-item">
            <summary>Mengapa tombol tertentu tidak muncul?</summary>
            <p>Tombol aksi akan muncul secara otomatis sesuai dengan tahapan proses permohonan Anda. Jika proses masih dalam pemeriksaan, tombol edit atau submit tidak ditampilkan.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa data tidak dapat diedit?</summary>
            <p>Setelah permohonan dikirim, formulir otomatis dikunci dari perubahan untuk menjaga integritas pemeriksaan. Akses edit akan dibuka kembali jika Admin Permohonan meminta revisi spesifik.</p>
        </details>
        <details class="faq-item">
            <summary>Mengapa order atau permohonan tidak muncul?</summary>
            <p>Pastikan Anda login menggunakan akun yang benar saat mengajukan permohonan. Permohonan hanya dapat dilihat oleh akun Klien pembuat permohonan.</p>
        </details>
        <details class="faq-item">
            <summary>Apa arti status yang sedang tampil?</summary>
            <p>Status pada daftar permohonan menggambarkan tahapan terkini, mulai dari pemeriksaan dokumen awal, proses pembayaran, evaluasi audit lapangan, hingga penerbitan sertifikat akhir.</p>
        </details>
        <details class="faq-item">
            <summary>Siapa yang harus dihubungi jika ada kendala?</summary>
            <p>Jika mengalami kendala pengisian atau memiliki pertanyaan seputar permohonan, silakan hubungi tim Admin Permohonan melalui kontak resmi yang tertera pada portal.</p>
        </details>
